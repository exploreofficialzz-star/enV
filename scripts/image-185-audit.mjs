// Audits the Images category: every catalog tool must open on a studio, every platform tool must resolve to a verified
// placement, and every hand-off target must exist. `--write` regenerates docs/image-implementation-audit.md.
// Run: node --experimental-strip-types scripts/image-185-audit.mjs [--write]
import fs from "node:fs";
import { parseGeneratedCatalog } from "./catalog-reader.mjs";
import { studioKindFor } from "../src/components/engines/image/tool-map.ts";
import { getPlacement, parsePlatformOp, PLATFORMS, SPEC_VERIFIED_ON } from "../src/lib/image/platform-presets.ts";
import { HANDOFF_TARGETS } from "../src/lib/image/handoff.ts";

const catalog = parseGeneratedCatalog(fs.readFileSync(new URL("../src/data/catalog.ts", import.meta.url), "utf8"));
const images = catalog.filter((t) => t.category === "image");
if (images.length !== 185) throw new Error(`Expected 185 image tools, found ${images.length}`);

const problems = [];
const rows = [];
const byStudio = new Map();
const confidence = { official: 0, documented: 0, approximate: 0 };
for (const t of images) {
  const op = t.engine?.op;
  if (!op) { problems.push(`${t.id}: no engine operation`); continue; }
  const kind = studioKindFor(op);
  if (!kind) problems.push(`${t.id} (${op}): still on the original engine`);
  byStudio.set(kind ?? "legacy", (byStudio.get(kind ?? "legacy") ?? 0) + 1);
  let note = "";
  const parsed = parsePlatformOp(op);
  if (parsed) {
    const p = getPlacement(parsed.platform, parsed.placement);
    if (!p) problems.push(`${t.id}: no placement for ${parsed.platform}/${parsed.placement}`);
    else if (parsed.kind === "compressor") note = `${PLATFORMS[parsed.platform].name} size limits`;
    else { const v = p.variants[0]; note = `${p.label} ${v.width}×${v.height} · ${p.confidence}${p.exists ? "" : " (no dedicated placement)"}`; confidence[p.confidence]++; }
  }
  rows.push({ id: t.id, name: t.name, op, kind: kind ?? "legacy", note });
}
const ids = new Set(images.map((t) => t.id));
for (const h of HANDOFF_TARGETS) if (!ids.has(h.id)) problems.push(`hand-off target ${h.id} is not an Images tool`);

console.log(`Image catalog audit: ${images.length} tools. Studios: ${[...byStudio].map(([k, n]) => `${k}=${n}`).join(", ")}.`);
console.log(`Platform placements: ${confidence.official} official, ${confidence.documented} documented, ${confidence.approximate} approximate (checked ${SPEC_VERIFIED_ON}).`);
if (problems.length) { console.error(problems.map((p) => `  - ${p}`).join("\n")); process.exit(1); }

if (process.argv.includes("--write")) {
  const T = {
    effect: "Effect studio — declarative controls, instant preview, full-resolution refinement, presets, undo/redo, before/after",
    resize: "Resize studio — exact/percent/fit/fill, px·in·cm·mm, DPI, aspect lock, anchor, resampling, sharpening",
    compress: "Compress/convert studio — real encoded before/after, quality, target file size, dimensions, metadata policy",
    metadata: "Metadata studio — grouped inspector, lossless removal (all / GPS only), batch + ZIP, post-clean verification",
    platform: "Platform studio — verified presets with confidence labels, drag/zoom/position, safe-area guides, size-capped export",
    crop: "Crop studio — handles, ratios, exact pixels, rotate/straighten/flip; circle and profile-picture framing",
    analysis: "Analysis studio — histogram, palettes, colour picker/sampler, transparency checks",
    calc: "Calculator studio — image-derived (measured) vs typed (calculated) values with copyable results",
    compose: "Compose studio — reorderable lists, exact layout controls, splitter, before/after, difference map",
    mask: "Mask studio — colour-key cut-out + Erase/Restore brushes, redaction, background blur",
    annotate: "Annotate studio — editable objects (arrows, shapes, text, steps, redact/blur/pixelate) and meme text boxes",
    watermark: "Watermark studio — text/logo, drag placement, tiling, rotation, opacity, batch with per-file status + ZIP",
    favicon: "Favicon studio — real multi-size .ico, PNG icon set, manifest and HTML tags",
  };
  const md = [
    "# Images category — implementation audit",
    "",
    `Generated by \`scripts/image-185-audit.mjs --write\`. Platform sizes checked ${SPEC_VERIFIED_ON}.`,
    "",
    "Every one of the 185 Images tools opens on a purpose-built studio running on the shared image library (`src/lib/image/*`). All processing is local: no network requests, no API keys, nothing uploaded.",
    "",
    "## Studios",
    "",
    "| Studio | Tools | What it provides |",
    "| --- | ---: | --- |",
    ...[...byStudio].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} | ${T[k] ?? ""} |`),
    "",
    `## Platform placements`,
    "",
    `${confidence.official} official · ${confidence.documented} documented · ${confidence.approximate} approximate. *Approximate* means the platform publishes no spec (or has no such placement); the tool shows the closest documented shape and says so.`,
    "",
    "## Tools",
    "",
    "| Tool | Operation | Studio | Notes |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.name} (\`${r.id}\`) | \`${r.op}\` | ${r.kind} | ${r.note} |`),
    "",
  ].join("\n");
  fs.writeFileSync(new URL("../docs/image-implementation-audit.md", import.meta.url), md);
  console.log("Wrote docs/image-implementation-audit.md");
}
